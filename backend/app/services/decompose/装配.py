# -*- coding: utf-8 -*-
"""把拆解产物装配成界面要的段。

拆解出来的 structure.json 用的是管线自己的字段名（最强的一刻属于哪一类、
亲密行为、阶层落差……），界面和模板匹配用的是另一套名字。这一层负责改名，
再派生几个字段：三类行为合成一张「命中的行为」表、取最高档当这一段的尺度档、
按最强的一刻找最近的剧情点，从它身上取主角立场、经典桥段、有没有旁人。

字段名以调好的原型为准，别在这里自己改。

一段的装配逻辑，去掉了片源和帧这些只有研究
脚本才用的路径字段——app 里视频由 Part 自己管。
"""
from . import grade as G

主角叫法 = {'施加方': '动手', '承受方': '挨打', '都不是': '都不是', None: '都不是'}


def _档(名, table):
    for lv, 词们 in table.items():
        if 名 in 词们:
            return lv
    return 0


def _最近的剧情点(pts, t):
    """最强的一刻落在哪个剧情点上。它决定这一段的主角立场和经典桥段。"""
    q = [p for p in pts if p.get('时间') is not None]
    if not q:
        return None
    if t is None:
        return q[0]
    return min(q, key=lambda x: abs(x['时间'] - t))


def 一段(s: dict, 序: int) -> dict:
    起, 止 = s.get('_起'), s.get('_止')
    时长 = s.get('_段时长') or ((止 - 起) if (起 is not None and 止 is not None) else 0)
    峰 = s.get('最强的一刻时间')
    pts = s.get('剧情点') or []
    近 = _最近的剧情点(pts, 峰)

    命中, 本能 = [], []
    for 类, table in (('亲密', G.INT), ('暴力', G.VIO), ('羞辱', G.HUM)):
        for e in s.get(f'{类}行为') or []:
            名 = G.canon(e.get('行为'), table)
            命中.append({'类': 类, '行为': 名, '时间': e.get('时间'),
                         '档': _档(名, table)})
        if s.get(f'{类}行为'):
            本能.append(类)
    # 没命中任何行为词就是 0 档，这是定义好的取值，不是缺数据
    尺度 = max([x['档'] for x in 命中], default=0)

    # 一段里有好几个剧情点，挑最强的那一刻所属的那条当代表，用来定这一段的类型
    类别 = s.get('最强的一刻属于哪一类') or (近 or {}).get('哪一类')

    前摇 = 0.0
    if 峰 is not None and 时长:
        前摇 = min(1.0, max(0.0, (峰 - (起 or 0)) / 时长))

    return {
        '段序号': 序,
        '起': round(起 or 0, 2),
        '止': round(止 or 0, 2),
        '段时长': round(时长, 2),
        '这段算哪种戏': 类别,
        '最强的一刻': s.get('最强的一刻'),
        '最强的一刻在第几秒': 峰,
        '钩子来得多早': round(前摇, 2),
        '主角是动手还是挨打': 主角叫法.get((近 or {}).get('主角在这一刻是'), '都不是'),
        '本能刺激': 本能,
        '段的尺度档': 尺度,
        '命中的行为': 命中,
        '哪种经典桥段': (近 or {}).get('高转化场景') or '都不是',
        '有没有旁人在看': (近 or {}).get('有旁人在看吗') or '无',
        '有没有身份差距': s.get('阶层落差') or '无',
        '亲密双方性别': s.get('亲密双方性别') or '无亲密场面',
        '结尾留没留悬念': s.get('结尾留没留悬念'),
        '留的是什么': s.get('留的是什么'),
        '段落叙述': s.get('段落叙述') or '',
        '地点': (s.get('场景') or {}).get('地点'),
        '看没看成': s.get('_看成了'),
        '每分钟几件事': s.get('事件密度'),
        '每分钟几句台词': s.get('台词密度'),
        '剧情点': pts,
        # score.py 并段之后写回来的：区间重叠的剧情点并成一条，留分最高的当代表
        '剧情片段': s.get('剧情片段') or [],
        '段内最高剧情分': s.get('段内最高剧情分'),
        # hl.py 打的四个分。不合成总分——四维平均会把「情绪 9、脱上下文 3」
        # 和「四个都 5.5」排到一起，而这两场要用在完全不同的格里。
        '抓人速度': s.get('抓人速度'),
        '撑不撑得住': s.get('撑不撑得住'),
        '情绪强度': s.get('情绪强度'),
        '离开上下文看不看得懂': s.get('离开上下文看不看得懂'),
    }


def 装配(产物: dict) -> list:
    return [一段(s, i + 1) for i, s in enumerate(产物.get('段') or [])]

# -*- coding: utf-8 -*-
"""按剪辑模板从段库里挑段、排出成片计划。

算法和分值见下面的 分值 / 结构分值 两张表，
数据源从扫目录读 structure.json 换成查 admake_segments。

产出的计划表跟高光钩子那条路同形状（file_path / start / end / label /
part_name / score），后面的裁切、拼接、命名、日志、重试原样复用。
"""
import statistics

# 内容条件的分值。改这里等于改模板的匹配口径，所有模板的匹配度会跟着变。
分值 = {
    '最强的一刻属于哪一类': 3,
    '主角在这一刻是': 2,
    '本能刺激': 2,
    '高转化场景': 1,
    # 这两项只有「有」「无」两个值，一部剧里大半段都是「无」。对上了不说明两段像，
    # 对不上却要按整分扣，跨剧套模板时它们最容易把该选的段压下去。给半分。
    '有没有旁人在看': 0.5,
    '阶层落差': 0.5,
}
结构分值 = {
    '最强的一刻位置': 1,
    '结尾留没留悬念': 1,
}
# 开场那一格才写。爆款靠前三秒留人，复刻开场就得要求这部剧的段也留得住人，
# 否则一条结构对、开头平的片子照样跑不动。单独算分，见 抓人得分。
抓人分值 = 2

# 模板用的是拆解管线那套字段名，段库里存的是界面那套。差异只在这张表上。
模板名到库名 = {
    '最强的一刻属于哪一类': '这段算哪种戏',
    '主角在这一刻是': '主角是动手还是挨打',
    '本能刺激': '本能刺激',
    '高转化场景': '哪种经典桥段',
    '有没有旁人在看': '有没有旁人在看',
    '阶层落差': '有没有身份差距',
}


def _要的值(v):
    """枚举条件写数组是取其一，写字符串是必须等于它。统一成集合。"""
    if v is None:
        return None
    return set(v) if isinstance(v, (list, tuple, set)) else {v}


def 段字典(seg, part, 序号) -> dict:
    """把一行 AdmakeSegment 摊成算分用的字典。

    起止用的是 Part 内的绝对秒，跟播放器、导轨和裁切是同一条时间轴。
    """
    f = seg.fields or {}
    时长 = float(seg.duration_sec or 0) or 1.0
    # 段库里这个比值已经算好存成「钩子来得多早」。这里原来读的是「最强的一刻时间」，
    # 段库里根本没有这个键，于是每一段的前摇都恒等于 0.5，「最强的一刻位置」这条
    # 结构条件在任何模板上都判不通过——实测 279 段里本该有 15 段在前四分之一、
    # 131 段在后四分之一，一段都认不出来。
    早 = f.get('钩子来得多早')
    if 早 is None:
        峰 = f.get('最强的一刻在第几秒')
        早 = ((float(峰) - float(seg.start_sec)) / 时长) if 峰 is not None else 0.5
    前摇 = float(早)
    刺激 = f.get('本能刺激')
    if isinstance(刺激, str):
        刺激 = [刺激]
    return {
        '段ID': f'P{序号}-{seg.seg_index}',
        'id': seg.id,
        'part_id': seg.part_id,
        '片序': 序号,
        'part_name': getattr(part, 'name', '') or '',
        'file_path': getattr(part, 'file_path', None),
        '起': float(seg.start_sec or 0),
        '止': float(seg.end_sec or 0),
        '段时长': 时长,
        '这段算哪种戏': seg.seg_type or None,
        '段的尺度档': int(seg.intensity or 0),
        '前摇占比': max(0.0, min(1.0, 前摇)),
        '主角是动手还是挨打': f.get('主角是动手还是挨打'),
        '本能刺激': list(刺激 or []),
        '哪种经典桥段': f.get('哪种经典桥段'),
        '有没有旁人在看': f.get('有没有旁人在看'),
        '有没有身份差距': f.get('有没有身份差距'),
        '结尾留没留悬念': f.get('结尾留没留悬念'),
        '每分钟几件事': f.get('每分钟几件事'),
        '每分钟几句台词': f.get('每分钟几句台词'),
        '抓人速度': f.get('抓人速度'),
        '情绪强度': f.get('情绪强度'),
        '离开上下文看不看得懂': f.get('离开上下文看不看得懂'),
        '一句话': f.get('最强的一刻') or (f.get('段落叙述') or '')[:40],
    }


def 原片各格多长(格们):
    """爆款那条片子每一格多少秒。存模板时逐格记下来了，内置模板没有这个数。"""
    秒 = [float(g.get('段时长') or 0) for g in 格们]
    return 秒 if all(x > 0 for x in 秒) else None


def 补几段(格们, 要补):
    """多出来的段派给谁。

    按原片每格多长按比例派：爆款开场 6 秒、中段 30 秒，就该中段多拿。
    模板没记原片段长时（内置模板），中段先拿，其次结尾，开场排最后——开场是钩子，
    一段讲完；在钩子后面接一段凑时长，等于把观众要等的那个点往后推。
    """
    N = len(格们)
    补 = [0] * N
    if 要补 <= 0 or N == 0:
        return 补
    秒 = 原片各格多长(格们)
    if 秒:
        总 = sum(秒)
        配 = [要补 * x / 总 for x in 秒]
        补 = [int(x) for x in 配]
        # 按小数部分从大到小把除不尽的那几段派完
        for i in sorted(range(N), key=lambda i: -(配[i] - 补[i]))[:要补 - sum(补)]:
            补[i] += 1
        return 补
    顺序 = list(range(1, N - 1)) + ([N - 1] if N > 1 else []) + [0]
    for j in range(要补):
        补[顺序[j % len(顺序)]] += 1
    return 补


def 段分配(格们, 目标时长, 库):
    """时长摊到每一段上，不摊到每一格上。

    模板的格数来自爆款素材，跟这部剧的段长分布无关；按格摊会摊出段库够不着的区间。
    """
    M = statistics.median([s['段时长'] for s in 库]) if 库 else 0
    M = M or 1.0
    N = max(len(格们), 1)
    装得下 = max(1, int(目标时长 / M + 0.5))
    段数上限 = N * 4
    K = min(max(装得下, N), 段数上限)
    取几段 = [1 + x for x in 补几段(格们, K - N)]
    for i, g in enumerate(格们):
        取几段[i] = max(取几段[i], g.get('取几段') or 1)
    总段数 = sum(取几段)
    # 时长不再当硬条件。模板复刻的是结构，格里本来就没写秒数；目标时长只用来定
    # 一条填几段，再给每段一个「理想段长」，同匹配度的段里挑离它近的。
    # 每格各有各的理想段长：原片开场 6 秒的，这边也该挑短段，不能拿全片平均去套。
    秒 = 原片各格多长(格们)
    if 秒:
        总 = sum(秒)
        每格理想 = [round(目标时长 * 秒[i] / 总 / 取几段[i], 1) for i in range(N)]
    else:
        每格理想 = [round(目标时长 / 总段数, 1)] * N
    return {'中位段长': round(M, 1), '装得下几段': 装得下, '段数上限': 段数上限,
            '总段数': 总段数, '每格取几段': 取几段,
            '每格理想段长': 每格理想,
            '理想段长': round(目标时长 / 总段数, 1)}


def 筛段(库, 格):
    """没有硬条件了。尺度档以前是上限、当硬条件筛，大尺度的模板反而拦不住小尺度
    的段进来，而更大尺度的段一个都进不来。现在尺度档是目标，进匹配度里算分。"""
    return list(库)


def 尺度目标(格):
    """这一格想要的尺度档。老模板写的是「尺度档上限」，拿它当目标用。"""
    c = 格.get('内容条件') or {}
    v = c.get('尺度档', c.get('尺度档上限'))
    return None if v is None else int(v)


尺度分值 = 2


def 尺度得分(段, 目标):
    """同档满分，差一档一半，差得更多不得分。"""
    差 = abs(int(段['段的尺度档']) - 目标)
    return 尺度分值 if 差 == 0 else (尺度分值 / 2 if 差 == 1 else 0)


# 主角立场有两种写法：拆解管线原始产物写「施加方／承受方」，装配层映射成
# 「动手／挨打」存进段库，模板里写的也是后者。段库里混进旧写法时照样要能对上。
主角归一 = {'施加方': '动手', '承受方': '挨打'}


def 对得上(段, k, 要):
    if k == '本能刺激':
        return bool(set(段['本能刺激']) & 要)
    v = 段.get(模板名到库名[k])
    if k == '主角在这一刻是':
        v = 主角归一.get(v, v)
        要 = {主角归一.get(x, x) for x in 要}
    return v in 要


def 结构对得上(段, k, 要):
    if k == '最强的一刻位置':
        p = 段['前摇占比']
        实 = '前四分之一' if p < 0.25 else ('后四分之一' if p > 0.75 else '中间')
        return 实 == 要
    if k == '结尾留没留悬念':
        return 段['结尾留没留悬念'] == 要
    return False


def 抓人得分(段, 要, 权):
    """抓人速度这一条单独算，因为它有第三种情况：这一段压根没打出分。

    判 True 等于白送满分，会把预检里的「六成以上」抬高，而排序时它又被排到最后，
    用户看到的可用条数比实际能用的多；判 False 又会把没打过分的段全打死。
    按一半算：不确定就不偏向任何一边。
    """
    v = 段.get('抓人速度')
    if v is None:
        return 权 / 2
    return 权 if float(v) >= 要 else 0


def 打分(段, 格):
    """匹配度＝这一格声明的条件里满足了多少。模板里缺省的项不计入分母。"""
    c = 格.get('内容条件') or {}
    q = 格.get('结构条件') or {}
    得, 满 = 0, 0
    for k, w in 分值.items():
        要 = _要的值(c.get(k))
        if 要 is None:
            continue
        满 += w
        if 对得上(段, k, 要):
            得 += w
    for k, w in 结构分值.items():
        要 = q.get(k)
        if 要 is None:
            continue
        满 += w
        if 结构对得上(段, k, 要):
            得 += w
    目标 = 尺度目标(格)
    if 目标 is not None:
        满 += 尺度分值
        得 += 尺度得分(段, 目标)
    要速 = q.get('抓人速度下限')
    if 要速 is not None:
        满 += 抓人分值
        得 += 抓人得分(段, 要速, 抓人分值)
    分 = 1.0 if not 满 else round(得 / 满, 3)
    # 段类型是这一格的定义：开场要冲突，就不能拿一场情绪戏去填。它只占 3 分，
    # 而分母常见 8 到 13，类型完全不对、别的都对，照样能到 0.7，跟着就被算进
    # 预检的「六成以上」。实测「爽点反转冲突」第一格的 37 个候选里 20 个类型不是
    # 爽点。类型不对的一律压到六成线以下：还能排进候选，但不再冒充可用。
    需 = _要的值(c.get('最强的一刻属于哪一类'))
    if 需 is not None and not 对得上(段, '最强的一刻属于哪一类', 需):
        分 = min(分, 0.55)
    return 分


def 位置(格, i, 共几格):
    """这一格算开场、结尾还是中段。

    模板里写了「锁位置」就听它的，没写按它在数组里的次序定。这个字段以前没有
    任何代码读，改了不起作用——现在它决定同分时按什么排。
    """
    锁 = (格 or {}).get('锁位置')
    if 锁 == '第一格':
        return True, False
    if 锁 == '最后一格':
        return False, True
    if 锁 == '不锁':
        return False, False
    return i == 0, i == 共几格 - 1


def 排序键(段, 格, 第一格, 末格=False, 理想段长=None):
    """先按匹配度降序，同分再按位置排，再按离理想段长多近排。

    第一格看抓人速度——前三秒决定观众还往不往下看；末格看情绪强度——收尾要靠
    一个情绪高点停住；中间格按事件密度。没打过分的段退回代理指标。
    时长排在最后：它只在前面几项都一样时起作用，成片长短靠它往目标时长靠，不筛段。
    """
    if 第一格:
        序 = (-(段.get('抓人速度') or 0), -(段.get('离开上下文看不看得懂') or 0), 段['前摇占比'])
    elif 末格:
        序 = (-(段.get('情绪强度') or 0), -(float(段['每分钟几件事'] or 0)))
    else:
        序 = (-(float(段['每分钟几件事'] or 0)),)
    # 时长分四档，档内才比这一格自己的指标。原来时长排在最后一位，而中段格比的是
    # 事件密度这种连续值，几乎不可能并列，时长那一档永远轮不到——实测目标 6 分钟
    # 导出来的成片在 3 分 47 秒到 9 分 33 秒之间。分档之后，匹配度仍然优先，
    # 长度接近的段里再挑这一格最想要的那个。
    远 = abs(段['段时长'] - 理想段长) if 理想段长 else 0
    档 = min(3, int(远 / max(理想段长 * 0.25, 1))) if 理想段长 else 0
    return (-打分(段, 格), 档, 序, 远, 段['段ID'])


结构叫法 = {'最强的一刻位置': '最强的一刻', '结尾留没留悬念': '结尾',
            '抓人速度下限': '抓人速度'}

条件叫法 = {'最强的一刻属于哪一类': '段类型', '主角在这一刻是': '主角',
            '本能刺激': '本能刺激', '高转化场景': '经典桥段',
            '有没有旁人在看': '旁人', '阶层落差': '身份差距'}


def 条件说法(k, 要):
    值 = '或'.join(str(x) for x in sorted(要, key=str))
    if k == '有没有旁人在看':
        return '要有旁人在看' if 值 == '有' else '要没有旁人在看'
    if k == '阶层落差':
        return '要有身份差距' if 值 == '有' else '要没有身份差距'
    return f'{条件叫法.get(k, k)}要{值}'


def 条件一句话(格):
    """预检表上那一列。写全这一格在按什么打分，否则用户看到「不挑」，
    实际上每一段都在为没写出来的那几条掉分。"""
    c = 格.get('内容条件') or {}
    q = 格.get('结构条件') or {}
    出 = [条件说法(k, _要的值(c[k])) for k in 分值 if _要的值(c.get(k)) is not None]
    档 = 尺度目标(格)
    if 档 is not None:
        出.append(f'尺度档要 {档}')
    if q.get('最强的一刻位置'):
        出.append(f'最强的一刻在{q["最强的一刻位置"]}')
    if q.get('结尾留没留悬念'):
        出.append('结尾留悬念' if q['结尾留没留悬念'] == '留了' else '结尾不留悬念')
    速 = q.get('抓人速度下限')
    if 速 is not None:
        出.append(f'抓人速度不低于 {速}')
    return '，'.join(出) or '不挑'


def 内容对不上(候选, 格):
    """这一格声明了、但候选段里一段都对不上的条件。候选为空时不列。"""
    if not 候选:
        return []
    c = 格.get('内容条件') or {}
    出 = []
    for k in 分值:
        要 = _要的值(c.get(k))
        if 要 is None:
            continue
        if not any(对得上(s, k, 要) for s in 候选):
            出.append(条件说法(k, 要))
    目标 = 尺度目标(格)
    if 目标 is not None and not any(int(s['段的尺度档']) == 目标 for s in 候选):
        出.append(f'尺度档要 {目标}')
    return 出


def 筛空了怎么办(库, 格):
    """某一格一段候选都没有。没有硬条件之后只剩一种情况：段库是空的。"""
    return '这个项目还没有拆出段，先跑一次 AI 分析。'


def 算匹配(库, 格们, 目标时长, 要几条=3):
    """导出前的预检：每一格有多少候选、最高匹配度多少、推荐导几条。"""
    分配 = 段分配(格们, 目标时长, 库)
    每格, 撑得起 = [], []
    for i, g in enumerate(格们):
        取几段 = 分配['每格取几段'][i]
        理想 = 分配['每格理想段长'][i]
        cand = 筛段(库, g)
        开, 末 = 位置(g, i, len(格们))
        cand.sort(key=lambda s: 排序键(s, g, 开, 末, 理想))
        分 = sorted((打分(s, g) for s in cand), reverse=True)
        够格 = sum(1 for x in 分 if x >= 0.6)
        # 这一格撑得起几条：选段只要还有没用过的段就不回头复用，所以能出的条数是
        # 六成以上的候选数除以这一格要填几段。原来乘 3 是按「同一个段最多进 3 条」
        # 算的，而复用只在候选用光之后才发生，那 3 倍拿不到——实测推荐 9 条时，
        # 45 个槽里 13 个掉到六成以下，最低 12.5%。
        # 六成以上一个都没有时给 0，不要退回按候选总数算：那会在最该报警的时候
        # 报出一个正数。
        撑得起.append(够格 // max(取几段, 1))
        每格.append({
            '序': g.get('序', i + 1),
            '格名': g.get('格名') or f'第{i + 1}格',
            '条件一句话': 条件一句话(g),
            '取几段': 取几段,
            '通过硬条件': len(cand),
            '最高匹配度': 分[0] if 分 else None,
            '六成以上': 够格,
            '内容对不上的条件': 内容对不上(cand, g),
            '候选': [{'段ID': s['段ID'], '匹配度': 打分(s, g),
                      '段时长': round(s['段时长'], 1), '一句话': s['一句话']}
                     for s in cand[:10]],
        })
    拦, 因, 提醒 = False, None, None
    空 = [(i, x) for i, x in enumerate(每格) if x['通过硬条件'] == 0]
    if 空:
        i, x = 空[0]
        拦 = True
        因 = f'第 {x["序"]} 格「{x["格名"]}」一段都筛不出来。' + 筛空了怎么办(库, 格们[i])
    elif len(库) < len(格们):
        拦 = True
        因 = (f'这部剧只拆出 {len(库)} 段，模板有 {len(格们)} 格，凑不出一条完整的。'
              f'换一个格数少的模板，或者多分析几个 Part。')
    推荐 = 0 if 拦 else min(10, min(撑得起) if 撑得起 else 0)
    # 六成以上的段不够填满一条，以前是拦住不让导。现在放行、只提醒：模板条件是
    # 偏好不是门槛，剪辑自己剪也会拿次优的段凑；成片里这几格会用匹配度低的段，
    # 计划表和导出日志都标了匹配度，用户看得见。
    if not 拦 and 推荐 == 0:
        # 卡住的是「六成以上 ÷ 这一格要填几段」最小的那一格，不是六成以上最少的
        # 那一格。两格要填的段数不一样时会指错，报出来的话自己打自己：
        # 「只有 2 个，不够填满一条（这一格要 1 段）」。
        差 = min(range(len(每格)),
                key=lambda i: 每格[i]['六成以上'] // max(每格[i]['取几段'], 1))
        x = 每格[差]
        提醒 = (f'第 {x["序"]} 格「{x["格名"]}」匹配六成以上的段只有 {x["六成以上"]} 个，'
                f'不够填满一条（这一格要 {x["取几段"]} 段），成片里这一格会用匹配度不到六成的段。')
        推荐 = 1
    # 预检也给一条成片的预计长度：时长不再筛段，成片多长要让用户在导出前看到
    预计 = None
    if not 拦:
        试 = 选段(库, 格们, 目标时长, 1)
        预计 = 试[0]['总时长'] if 试 else None
    return {'每格': 每格, '推荐条数': 推荐, '拦住了吗': 拦, '拦住的原因': 因, '提醒': 提醒,
            '总段数': 分配['总段数'], '中位段长': 分配['中位段长'],
            '理想段长': 分配['理想段长'], '目标时长': round(目标时长, 1), '预计成片时长': 预计}


def 选段(库, 格们, 目标时长, 要几条=3):
    """同一条成片内段不重复；不同成片可以共用段，同一个段最多进 3 条。"""
    分配 = 段分配(格们, 目标时长, 库)
    排好 = []
    for i, g in enumerate(格们):
        cand = 筛段(库, g)
        开, 末 = 位置(g, i, len(格们))
        cand.sort(key=lambda s: 排序键(s, g, 开, 末, 分配['每格理想段长'][i]))
        排好.append(cand)
    名次 = [{x['段ID']: j for j, x in enumerate(c)} for c in 排好]

    用过, 成片, 出过 = {}, [], set()
    for 条 in range(1, 要几条 + 1):
        本条 = set()
        选中 = [[] for _ in 格们]

        def 挑一段(i):
            剩 = [s for s in 排好[i] if s['段ID'] not in 本条 and 用过.get(s['段ID'], 0) < 3]
            if not 剩:
                剩 = [s for s in 排好[i] if s['段ID'] not in 本条]
            if not 剩:
                return None
            # 用得少的排前面，几条成片才不会长一个样；候选用完了才回头复用
            剩.sort(key=lambda s: (用过.get(s['段ID'], 0), 名次[i][s['段ID']]))
            s = 剩[0]
            本条.add(s['段ID'])
            用过[s['段ID']] = 用过.get(s['段ID'], 0) + 1
            选中[i].append(s)
            return s

        # 先给每一格各留一段，再把剩下的名额分下去。不先留，候选少的时候前面的格
        # 会把段全占光，后面的格一段都填不上，整格从成片里消失。
        for i in range(len(格们)):
            挑一段(i)
        for i in range(len(格们)):
            for _ in range(分配['每格取几段'][i] - len(选中[i])):
                if 挑一段(i) is None:
                    break

        段们 = []
        for i, g in enumerate(格们):
            # 一格填几段是按时长算出来的，挑的时候按匹配度排，放进成片要按原片先后放。
            # 照匹配度的名次放，同一格里第二段可能发生在第一段之前，剧情是倒着走的。
            for s in sorted(选中[i], key=lambda x: (x['片序'], x['起'])):
                段们.append({**s, '填的是哪一格': g.get('格名') or f'第{i + 1}格',
                            '匹配度': 打分(s, g)})
        if not 段们:
            break
        # 段库撑不住更多条时，后面几条会挑到跟前面一模一样的段。再出就是复制品，
        # 每条还要花一份渲染时间，所以到这里就收。
        签 = frozenset(x['段ID'] for x in 段们)
        if 签 in 出过:
            break
        出过.add(签)
        成片.append({'序': 条, '总时长': round(sum(x['段时长'] for x in 段们), 1),
                    '段': 段们,
                    # 有几段没到六成。跨格抢段之后靠后的成片会往下够，
                    # 不标出来的话只能人工翻每条日志才看得见。
                    '低于六成': sum(1 for x in 段们 if x['匹配度'] < 0.6)})
    return 成片


def 排成计划(段们) -> list[dict]:
    """把选出来的段排成 _run_export_multi 认的计划表。

    它只读 file_path、start、end 三个键，_write_export_log 另读 label、
    part_name、score。形状对上就能原样复用后面整条出片链路。
    """
    return [{
        'file_path': s['file_path'],
        'part_id': s['part_id'],
        'start': round(s['起'], 2),
        'end': round(s['止'], 2),
        'label': 'segment',
        'part_name': s['part_name'],
        'score': round(s['匹配度'] * 10, 1),
        'seg_id': s['段ID'],
        'slot': s['填的是哪一格'],
    } for s in 段们]
